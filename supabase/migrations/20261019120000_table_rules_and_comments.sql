-- Official website uniqueness matches the API: trim, lowercase, drop trailing slashes.
do $$
declare
  dup_count integer;
begin
  select count(*) into dup_count
  from (
    select regexp_replace(lower(btrim(official_website)), '/+$', '') as website
    from public.hackathons
    group by 1
    having count(*) > 1
  ) duplicates;

  if dup_count > 0 then
    raise exception
      'Cannot rebuild official_website unique index: % website value(s) differ only by case or a trailing slash. Merge those rows, then run this migration again.',
      dup_count;
  end if;
end
$$;

drop index if exists public.hackathons_official_website_unique;

create unique index hackathons_official_website_unique
  on public.hackathons (regexp_replace(lower(btrim(official_website)), '/+$', ''));

comment on index public.hackathons_official_website_unique is
  'One row per official website after trim, lowercase, and stripping trailing slashes.';

-- Recreate updated_at triggers so this script can be run more than once by hand.
drop trigger if exists hackathons_set_updated_at on public.hackathons;
create trigger hackathons_set_updated_at
before update on public.hackathons
for each row execute function public.set_updated_at();

drop trigger if exists organizer_followups_set_updated_at on public.organizer_followups;
create trigger organizer_followups_set_updated_at
before update on public.organizer_followups
for each row execute function public.set_updated_at();

alter table public.hackathons drop constraint if exists hackathons_evidence_links_array;
alter table public.hackathons
  add constraint hackathons_evidence_links_array
  check (jsonb_typeof(evidence_links) = 'array')
  not valid;

alter table public.hackathons drop constraint if exists hackathons_verified_rules;
alter table public.hackathons
  add constraint hackathons_verified_rules
  check (
    status not in ('Verified - Apply Now', 'Verified - Registration Upcoming')
    or (
      jsonb_typeof(evidence_links) = 'array'
      and jsonb_array_length(evidence_links) > 0
      and verifier_name is not null
      and length(btrim(verifier_name)) > 0
      and confidence <> 'Low'
      and (
        researcher_name is null
        or length(btrim(researcher_name)) = 0
        or lower(btrim(researcher_name)) <> lower(btrim(verifier_name))
      )
    )
  )
  not valid;

alter table public.hackathons drop constraint if exists hackathons_shortlist_rationale_required;
alter table public.hackathons
  add constraint hackathons_shortlist_rationale_required
  check (
    is_shortlisted = false
    or (
      shortlist_rationale is not null
      and length(btrim(shortlist_rationale)) > 0
    )
  )
  not valid;

alter table public.organizer_followups drop constraint if exists organizer_followups_pending_has_no_answer;
alter table public.organizer_followups
  add constraint organizer_followups_pending_has_no_answer
  check (
    response_status <> 'Pending'
    or confirmed_answer is null
    or length(btrim(confirmed_answer)) = 0
  )
  not valid;

